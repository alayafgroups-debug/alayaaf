const getInitialLocale = (): Locale => {
  if (typeof window === "undefined") return "ar";
  return window.localStorage.getItem("app_language") === "en" ? "en" : "ar";
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);
  const direction: Direction = locale === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = direction;
    document.body.dir = direction;
  }, [locale, direction]);

  useEffect(() => {
    const restoreUserPreference = async () => {
      if (
        typeof window === "undefined" ||
        window.localStorage.getItem("app_language")
      )
        return;
      const session = readUserSession();
      if (!session?.empId) return;
      const { data } = await supabase
        .from("user_preferences")
        .select("preferences")
        .eq("emp_id", session.empId)
        .maybeSingle();
      const savedLocale = (data?.preferences as { lang?: string } | null)?.lang;
      if (savedLocale === "ar" || savedLocale === "en")
        setLocaleState(savedLocale);
    };
    void restoreUserPreference();
  }, []);

  const setLocale = async (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    localStorage.setItem("app_language", nextLocale);
    const session = readUserSession();
    if (!session?.empId) return;
    const { data } = await supabase
      .from("user_preferences")
      .select("preferences")
      .eq("emp_id", session.empId)
      .maybeSingle();
    await supabase.from("user_preferences").upsert(
      {
        emp_id: session.empId,
        preferences: {
          ...((data?.preferences as object) ?? {}),
          lang: nextLocale,
        },
        updated_at: new Date().toISOString(),
      },
      { onConflict: "emp_id" },
    );
  };

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      direction,
      t: (source) =>
        locale === "en" ? (translations[source] ?? source) : source,
      setLocale,
      formatDate: (date, options) =>
        new Intl.DateTimeFormat(
          locale === "ar" ? "ar-SA" : "en-US",
          options,
        ).format(new Date(date)),
      formatNumber: (number, options) =>
        new Intl.NumberFormat(
          locale === "ar" ? "ar-SA" : "en-US",
          options,
        ).format(number),
    }),
    [locale, direction],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
